// 「ヶ」と「ケ」を相互変換した別表記を返す
function altKatakanaKe(name) {
  if (name.includes('ヶ')) return name.replace(/ヶ/g, 'ケ')
  if (name.includes('ケ')) return name.replace(/ケ/g, 'ヶ')
  return null
}

// 都道府県 + 市区町村 → [lat, lng] or null
//   段階的フォールバック:
//     1. 完全一致 (e.g. "札幌市", "茅ヶ崎市")
//     2. ヶ↔ケ 表記揺れ (e.g. "龍ヶ崎市" → "龍ケ崎市")
//     3. 政令市区→市 (e.g. "札幌市中央区" → "札幌市")
//     4. 郡省略 (e.g. "石狩郡当別町" → "当別町") + ヶ↔ケ 補正
//     5. 自治体合併・改称オーバーライド (e.g. "丹波篠山市")
export function lookupMunicipalityGeo(prefecture, city) {
  if (!prefecture || !city) return null

  // 1. 完全一致
  if (geo[prefecture]?.[city]) return geo[prefecture][city]

  // 2. ヶ↔ケ
  const alt = altKatakanaKe(city)
  if (alt && geo[prefecture]?.[alt]) return geo[prefecture][alt]

  // 3. 政令市区
  const m1 = city.match(/^(.+?市)(.+区)$/)
  if (m1 && geo[prefecture]?.[m1[1]]) return geo[prefecture][m1[1]]

  // 4. 郡省略 (e.g. "石狩郡当別町" → "当別町")
  const m2 = city.match(/^.+?郡(.+[町村])$/)
  if (m2) {
    const stripped = m2[1]
    if (geo[prefecture]?.[stripped]) return geo[prefecture][stripped]
    const altStripped = altKatakanaKe(stripped)
    if (altStripped && geo[prefecture]?.[altStripped]) return geo[prefecture][altStripped]
  }

  // 5. 手動オーバーライド (合併・改称)
  if (OVERRIDES[prefecture]?.[city]) return OVERRIDES[prefecture][city]

  return null
}

// 都道府県のみ → [lat, lng] (県庁所在地)
export function lookupPrefectureGeo(prefecture) {
  return PREFECTURE_CENTROIDS[prefecture] ?? null
}

// ユーザー住所 → 緯度経度 (市町村優先、市町村が解決できないか未設定なら都道府県)
export function resolveUserGeo(prefecture, city) {
  if (city) {
    const m = lookupMunicipalityGeo(prefecture, city)
    if (m) return m
  }
  return lookupPrefectureGeo(prefecture)
}
