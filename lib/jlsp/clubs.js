/** 基準クラブ一覧。vector は RAW_CLUBS のもの (DB の override 未適用)。
 *  実際の診断ロジックでは server 側で DB の vector override を適用したものを使う。
 */
export const CLUBS = RAW_CLUBS

/** RAW_CLUBS が持つ素の vector (overrides 適用前) を id をキーに引けるマップ。*/
export const BASE_VECTORS = Object.fromEntries(RAW_CLUBS.map((c) => [c.id, c.vector]))

/** RAW_CLUBS の vector に override を被せた配列を返す純粋関数。
 *  loader.js から DB の vector override と組み合わせて使う。
 */
export function applyVectorOverrides(overrides) {
  if (!overrides || Object.keys(overrides).length === 0) return RAW_CLUBS
  return RAW_CLUBS.map((c) => {
    const o = overrides[c.id]
    if (!o) return c
    return { ...c, vector: { ...c.vector, ...o } }
  })
}
